#ifndef RML_SURFACE_RECONSTRUCTOR_H
#define RML_SURFACE_RECONSTRUCTOR_H

#include <array>
#include <cstdint>
#include <unordered_set>
#include <utility>
#include <vector>

#include "rml_node.h"

//! Reconstruction (retriangulation) of triangulated surfaces.
//!
//! The reconstructor works on an indexed set of linear triangles and never
//! moves existing nodes - it removes nodes and reconnects triangles and
//! optionally (quality meshing) inserts new nodes on the existing surface,
//! so the result stays within given tolerances of the input geometry.
//!
//! Following steps are performed:
//!  1. Edges shorter than minimum edge length are collapsed (tiny triangles).
//!     This is the only step which may change the shape - corners and dihedral
//!     features closer than minimum edge length are merged.
//!  2. Near-planar regions (coplanar triangles of the same surface) are found.
//!     Nodes inside a region and nodes on straight runs of region boundaries
//!     (feature lines) are removed and every region is retriangulated by
//!     constrained Delaunay triangulation (coplanar triangles are merged).
//!     Every new region patch is validated (same boundary with the same
//!     orientation, manifold, no flipped triangles), otherwise the original
//!     triangles of the region are kept together with all its nodes.
//!  3. Remaining sliver triangles are removed by collapsing their shortest
//!     edge (needles) or by flipping their longest edge (caps), provided the
//!     geometry is preserved within distance tolerance.
//!  4. Optionally (Options::delaunay) edges which are not locally Delaunay
//!     (sum of opposite angles above 180 degrees) are flipped, provided the
//!     geometry is preserved within distance tolerance and the edge is not
//!     locked, on a boundary or between different surfaces.
//!  5. Optionally (Options::refine) quality mesh is generated by Delaunay
//!     refinement (Ruppert's algorithm) of planar patches of the surface:
//!     new nodes are inserted at circumcenters of bad triangles (smallest
//!     angle below quality angle or edge longer than maximum edge length)
//!     and feature lines (patch boundaries, surface interfaces, boundaries)
//!     are split when encroached. New nodes lie on the existing surface,
//!     feature lines are split on their straight segments, so the shape is
//!     preserved. Inserted nodes inside planar patches are finally smoothed
//!     within their patch. Locked edges are never split.
//!
//! Locked nodes and edges (shared with elements outside of the processed set)
//! are always preserved, boundaries and interfaces between surfaces are never
//! pinched and the orientation of triangles is kept, so a closed consistently
//! oriented surface stays closed and consistently oriented.
//! If reconstruction creates new self-intersections, input triangles around
//! them are kept unchanged and the reconstruction is repeated.
class RSurfaceReconstructor
{

    public:

        //! Reconstruction options.
        struct Options
        {
            //! Angle tolerance [rad] - maximum angle between normals of
            //! coplanar triangles and between directions of collinear edges.
            double angleTolerance;
            //! Distance tolerance - maximum distance of a node from a plane
            //! (line) to be considered coplanar (collinear).
            //! Zero or negative value means automatic (1e-5 of bounding box diagonal).
            double distanceTolerance;
            //! Edges shorter than this are collapsed.
            //! Zero or negative value means automatic (10x distance tolerance).
            double minEdgeLength;
            //! Triangles with smallest angle [rad] below this value are slivers.
            double sliverAngle;
            //! Finish with Delaunay triangulation of the surface - edges are flipped
            //! while geometry is preserved within distance tolerance.
            bool delaunay;
            //! Quality meshing - insert new nodes (Delaunay refinement) so that
            //! triangles have smallest angle at least quality angle and edges are
            //! not longer than maximum edge length.
            bool refine;
            //! Target smallest angle [rad] of triangles when refining (clamped to 0-34 deg).
            double qualityAngle;
            //! Maximum edge length when refining. Zero or negative value means no limit.
            double maxEdgeLength;

            //! Constructor - default values.
            Options();
        };

        //! Reconstruction statistics.
        struct Statistics
        {
            //! Number of input triangles.
            uint nInputTriangles;
            //! Number of output triangles.
            uint nOutputTriangles;
            //! Number of nodes which are no longer used.
            uint nRemovedNodes;
            //! Number of collapsed edges.
            uint nCollapsedEdges;
            //! Number of flipped edges.
            uint nFlippedEdges;
            //! Number of planar regions.
            uint nPlanarRegions;
            //! Number of retriangulated regions.
            uint nRetriangulatedRegions;
            //! Number of regions for which retriangulation failed and original triangles were kept.
            uint nFailedRegions;
            //! Number of input triangles kept unchanged to avoid new self-intersections.
            uint nFrozenTriangles;
            //! Number of edges flipped by final Delaunay triangulation.
            uint nDelaunayFlips;
            //! Number of nodes inserted by quality refinement.
            uint nInsertedNodes;
            //! Number of inserted nodes moved by smoothing.
            uint nSmoothedNodes;

            //! Constructor.
            Statistics();
        };

        //! Triangle - node IDs and ID of the surface it belongs to.
        struct Triangle
        {
            std::array<uint,3> nodes;
            uint surfaceID;
        };

        //! Simple 3D vector.
        struct Vec3
        {
            double x, y, z;
        };

    protected:

        //! Internal triangle.
        struct Tri
        {
            int v[3];
            uint surfaceID;
            bool alive;
            //! Planar patch (quality refinement), -1 if not assigned.
            int patch;
        };

        //! Planar patch - plane and local 2D coordinate system (e1 x e2 = normal).
        struct Patch
        {
            Vec3 origin;
            Vec3 normal;
            Vec3 e1;
            Vec3 e2;
            //! Single triangle of a curved surface (smooth neighbors) - can not be refined
            //! without changing the shape, refinement would only spread over the surface.
            bool curvedFacet;
        };

        //! Model nodes.
        const std::vector<RNode> &nodes;
        //! Input triangles.
        std::vector<Triangle> inputTriangles;
        //! Input locked nodes.
        std::vector<bool> inputLockedNodes;
        //! Input locked edges.
        std::vector<std::pair<uint,uint>> inputLockedEdges;

        //! Options with resolved automatic values.
        Options options;
        //! Sine of angle tolerance.
        double sinAngleTolerance;
        //! Cosine of angle tolerance.
        double cosAngleTolerance;

        //! Local vertex positions.
        std::vector<Vec3> points;
        //! Local vertex to node ID map.
        std::vector<uint> vertexNodeIDs;
        //! Locked local vertices.
        std::vector<bool> lockedVertices;
        //! Locked local edges.
        std::unordered_set<uint64_t> lockedEdges;

        //! Triangles.
        std::vector<Tri> tris;
        //! Alive triangles incident to each vertex.
        std::vector<std::vector<int>> vertexTris;

        //! Segments (feature edges) which must not be flipped - quality refinement only.
        std::unordered_set<uint64_t> segments;
        //! Planar patches - quality refinement only.
        std::vector<Patch> patches;
        //! Original end vertices of the segment a new vertex was inserted on (-1 if not on segment).
        std::vector<std::array<int,2>> vertexSegments;
        //! Vertices inserted by quality refinement.
        std::vector<int> insertedVertices;
        //! New nodes created by last reconstruction.
        std::vector<RNode> newNodes;

    public:

        //! Constructor.
        //! Nodes must stay valid during the life of the reconstructor.
        //! lockedNodes is indexed by node ID (may be shorter than nodes - missing means unlocked).
        //! lockedEdges are pairs of node IDs.
        RSurfaceReconstructor(const std::vector<RNode> &nodes,
                              const std::vector<Triangle> &triangles,
                              const std::vector<bool> &lockedNodes,
                              const std::vector<std::pair<uint,uint>> &lockedEdges,
                              const Options &options = Options());

        //! Return options with resolved automatic values.
        const Options &getOptions() const;

        //! Perform reconstruction and return reconstructed triangles.
        //! Triangle orientation of the input is preserved.
        //! Node IDs greater or equal to the number of nodes refer to new nodes
        //! (see getNewNodes()), new node ID = number of nodes + position in new nodes.
        std::vector<Triangle> reconstruct(Statistics &statistics);

        //! Return new nodes created by last reconstruction (quality refinement).
        const std::vector<RNode> &getNewNodes() const;

    protected:

        //! Initialize working mesh from input triangles which are not frozen.
        //! Nodes and edges of frozen triangles are locked.
        void initialize(const std::vector<bool> &frozenTriangles);

        //! Run all reconstruction steps on working mesh and return resulting triangles.
        std::vector<Triangle> run(Statistics &statistics);

        //! Collapse edges shorter than minimum edge length.
        void collapseShortEdges(Statistics &statistics);

        //! Find planar regions and retriangulate them.
        void retriangulatePlanarRegions(Statistics &statistics);

        //! Remove sliver triangles.
        void removeSlivers(Statistics &statistics);

        //! Flip edges which are not locally Delaunay (Delaunay triangulation of the surface).
        void flipToDelaunay(Statistics &statistics);

        //! Perform Lawson flips over all triangles until mesh is (locally) Delaunay.
        //! Return number of flipped edges.
        uint flipAllToDelaunay();

        //! Quality refinement - insert new nodes.
        void refineMesh(Statistics &statistics);

        //! Find planar patches and segments for quality refinement.
        void findPatches();

        //! Check if triangle needs refinement.
        bool isBadTri(int t) const;

        //! Check if segment a-b needs to be split (encroached or too long).
        bool isSegmentToSplit(int a, int b) const;

        //! Find split point of segment a-b. Return false if the segment is too short to be split.
        bool findSegmentSplitPoint(int a, int b, Vec3 &point) const;

        //! Result of circumcenter insertion.
        enum class InsertResult
        {
            Inserted,
            SplitEdges,
            Failed
        };

        //! Try to insert circumcenter of triangle t.
        //! If edges must be split first they are returned in splitEdges.
        InsertResult insertCircumcenter(int t, int &newVertex, std::vector<std::pair<int,int>> &splitEdges);

        //! Split edge a-b at given point. Return new vertex or -1.
        int splitEdge(int a, int b, const Vec3 &point);

        //! Restore Delaunay property around vertex v.
        void legalize(int v);

        //! Smooth inserted vertices within their planar patches. Return number of moved vertices.
        uint smoothInsertedVertices();

        //! Add new vertex.
        int addVertex(const Vec3 &point);

        //! Project point to 2D coordinates of patch.
        void projectToPatch(int patch, const Vec3 &point, double &u, double &v) const;

        //! Check if edge is a segment.
        bool isSegment(int a, int b) const;

        //! Rebuild vertex to triangle map from alive triangles.
        void rebuildVertexTris();

        //! Kill triangle.
        void killTri(int t);

        //! Add triangle.
        int addTri(int v0, int v1, int v2, uint surfaceID);

        //! Return alive triangles sharing edge a-b.
        void findEdgeTris(int a, int b, std::vector<int> &edgeTris) const;

        //! Return vertices adjacent to given vertex.
        void findVertexNeighbors(int a, std::vector<int> &neighbors) const;

        //! Check if edge is locked.
        bool isLockedEdge(int a, int b) const;

        //! Check if edge a-b is a hard feature edge (boundary, non-manifold, locked
        //! or between different surfaces).
        bool isHardFeatureEdge(int a, int b) const;

        //! Check if edge a-b is a feature edge (boundary, non-manifold, locked,
        //! between different surfaces or with dihedral angle above tolerance).
        bool isFeatureEdge(int a, int b) const;

        //! Return raw (non-normalized, length = 2 x area) normal of triangle.
        Vec3 findTriNormal(int t) const;

        //! Return raw normal of triangle given by vertices.
        Vec3 findTriNormal(int v0, int v1, int v2) const;

        //! Check if triangle normal is reliable (triangle is not too thin).
        bool hasReliableNormal(int t) const;

        //! Check if normal of triangle given by vertices is reliable.
        bool hasReliableNormal(int v0, int v1, int v2) const;

        //! Return smallest angle of triangle given by vertices.
        double findMinAngle(int v0, int v1, int v2) const;

        //! Check if vertex a can be collapsed onto vertex b.
        bool canCollapse(int a, int b, bool shortEdge) const;

        //! Collapse vertex a onto vertex b.
        void collapse(int a, int b);

        //! Try to flip edge a-b of triangle t. Return true if flipped.
        //! If delaunay is true edge is flipped if it is not locally Delaunay, otherwise if quality improves.
        bool tryFlip(int t, int a, int b, bool delaunay);

        //! Return edge key.
        static uint64_t edgeKey(int a, int b);

};

#endif // RML_SURFACE_RECONSTRUCTOR_H
